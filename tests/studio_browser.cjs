/* Run the fixture server first. npm install --no-save playwright && npx playwright install chromium */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true, channel:process.env.STUDIO_BROWSER_CHANNEL || undefined});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage(), errors=[];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8766');
  await page.locator('#access-key').fill('studio-browser-test-key-12345678');
  await page.locator('#unlock-form button').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.locator('#chart-form button').click();
  await page.getByText('Price history loaded.', {exact:false}).waitFor();
  assert.match(await page.locator('#price').textContent(), /130/);
  await page.locator('nav [data-page=analysts]').click();
  await page.locator('#analyst-form [name=name]').fill('Skeptic');
  await page.locator('#analyst-form [name=instructions]').fill('Look for missing evidence. <script>alert(1)</script>');
  await page.locator('#analyst-form button:not([type=reset])').click();
  await page.locator('#analyst-list h2').getByText('Skeptic').waitFor();
  await page.locator('nav [data-page=setups]').click();
  await page.locator('#setup-form [name=name]').fill('Core research');
  await page.locator('#setup-form button').getByText('Save setup',{exact:true}).click();
  await page.locator('#setup-list h2').getByText('Core research').waitFor();
  await page.locator('#setup-form [name=name]').fill('Custom research');
  await page.locator('#custom-options input').check();
  await page.locator('#setup-form button').getByText('Save setup',{exact:true}).click();
  await page.locator('#setup-list h2').getByText('Custom research').waitFor();
  await page.locator('nav [data-page=dashboard]').click();
  await page.locator('#analysis-setup').selectOption({label:'Custom research'});
  await page.locator('#analysis-form button').click();
  await page.locator('#job-result h2').getByText('AAPL · Hold').waitFor();
  await page.getByText('Custom review: Skeptic',{exact:true}).click();
  assert.match(await page.locator('#job-result').textContent(), /<script>alert/);
  await page.locator('nav [data-page=scanner]').click();
  await page.locator('#scan-form button').click();
  await page.locator('#job-result table').waitFor();
  assert.match(await page.locator('#job-result').textContent(), /MSFT/);
  await page.locator('nav [data-page=backtest]').click();
  await page.locator('#backtest-form [name=start]').fill('2020-01-01');
  await page.locator('#backtest-form [name=end]').fill('2020-01-01');
  await page.locator('#backtest-setup').selectOption({label:'Core research'});
  assert.equal(await page.locator('#backtest-setup option').count(),2);
  await page.locator('#backtest-form button').click();
  await page.getByText('Fixture evaluation: one resolved cell.').waitFor();
  await page.locator('nav [data-page=portfolio]').click();
  await page.locator('#add-holding').click();
  await page.locator('[data-field=ticker]').fill('AAPL');
  await page.locator('[data-field=quantity]').fill('2');
  await page.locator('[data-field=average_price]').fill('100');
  await page.locator('#portfolio-form [name=cash]').fill('50');
  await page.locator('#portfolio-form button').getByText('Save portfolio',{exact:true}).click();
  await page.locator('#portfolio-list button').getByText('Value holdings →').click();
  await page.getByText('310 USD equity').waitFor();
  await page.reload();
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.locator('nav [data-page=setups]').click();
  assert.equal(await page.locator('#setup-list h2').count(),2);
  await page.locator('nav [data-page=dashboard]').click();
  await page.locator('#chart-form button').click();
  await page.getByText('Price history loaded.',{exact:false}).waitFor();
  const dir=process.env.STUDIO_SCREENSHOTS;
  if(dir){fs.mkdirSync(dir,{recursive:true}); await page.screenshot({path:dir+'/desktop.png',fullPage:true});}
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  if(dir) await page.screenshot({path:dir+'/mobile.png',fullPage:true});
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload();
  await context.setOffline(true);
  await page.reload();
  await page.locator('.brand').waitFor();
  const cached = await page.evaluate(async () => { const all=[]; for(const k of await caches.keys()) for(const r of await (await caches.open(k)).keys()) all.push(r.url); return all; });
  assert.equal(cached.some(url=>url.includes('/api/')),false);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: dashboard, custom analyst, setups, scanner, backtest, portfolio, persistence, XSS text, mobile layout, offline shell.');
})().catch(error=>{console.error(error);process.exit(1);});
